export interface SvgPoint {
  x: number;
  y: number;
  value: number;
}

export function buildChartGeometry(dailyValues: number[], maxScale = 1600000): {
  pathD: string;
  points: SvgPoint[];
} {
  const X_START = 85;
  const X_STEP = 145; // 85, 230, 375, 520, 665, 810, 955
  const Y_ZERO = 340;
  const Y_SPAN = 300; // Y=340 (0) to Y=40 (1.60M)

  const points: SvgPoint[] = dailyValues.slice(0, 7).map((value, idx) => {
    const x = X_START + idx * X_STEP;
    const ratio = Math.min(1, Math.max(0, value / maxScale));
    const y = Math.round(Y_ZERO - ratio * Y_SPAN);
    return { x, y, value };
  });

  const pathD = points.map((pt, i) => `${i === 0 ? 'M' : 'L'} ${pt.x},${pt.y}`).join(' ');
  return { pathD, points };
}

